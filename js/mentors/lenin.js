  function pickFragments(period, inputText, n) {
    // 参数兼容：pickFragments(period, n) 旧签名
    if (typeof inputText === 'number') { n = inputText; inputText = null; }
    n = n || 3;
    var periodNum = { standard: 0, period1: 1, period2: 2, period3: 3 }[period] || 0;

    // 如果提供了输入文本，做关键词相关性匹配
    var scored = FRAGMENTS.map(function (f) {
      var score = 0;
      if (f.period === periodNum || f.period === 0) score += 2; // 时期匹配加分
      if (inputText) {
        // 简单的关键词重叠：从片段中提取特征词，计算与输入的重叠数
        var fragWords = f.text.replace(/[，。、；：""''！？（）《》\s]/g, ' ').split(' ');
        var inputWords = inputText.replace(/[，。、；：""''！？（）《》\s]/g, ' ').split(' ');
        var overlap = 0;
        fragWords.forEach(function (fw) {
          if (fw.length >= 2 && inputText.indexOf(fw) !== -1) overlap++;
        });
        score += overlap;
      }
      return { fragment: f, score: score };
    });

    // 按得分降序排列
    scored.sort(function (a, b) { return b.score - a.score; });

    // 取前n个，加入一定随机性：从前n*2个中随机选n个
    var poolSize = Math.min(n * 2, scored.length);
    var candidates = scored.slice(0, poolSize);

    // Fisher-Yates on candidates
    for (var i = candidates.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var tmp = candidates[i]; candidates[i] = candidates[j]; candidates[j] = tmp;
    }

    return candidates.slice(0, n).map(function (c) { return c.fragment; });
  }

