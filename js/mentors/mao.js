  function pickFragments(period, n) {
    n = n || 3;
    var periodNum = { standard: 0, period1: 1, period2: 2, period3: 3 }[period] || 0;
    var pool = FRAGMENTS.slice();

    for (var i = pool.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var tmp = pool[i]; pool[i] = pool[j]; pool[j] = tmp;
    }

    var picked = [], rest = [];
    pool.forEach(function (f) {
      if (picked.length >= n) return;
      if (f.period === periodNum || f.period === 0) {
        if (picked.length < Math.ceil(n * 0.7)) picked.push(f);
        else rest.push(f);
      } else {
        rest.push(f);
      }
    });
    while (picked.length < n && rest.length > 0) picked.push(rest.shift());

    return picked;
  }

  function buildPrompt(text, period, inputType, fragments) {
    period = period || 'standard';
    // inputType 由父文件传入，毛泽东不使用（为接口统一保留）
    var pd = PERIODS[period] || PERIODS['standard'];
    if (!fragments || !Array.isArray(fragments) || fragments.length === 0) fragments = pickFragments(period, 3);

    var parts = [pd.systemPrompt];

    parts.push('');
    parts.push('【经典片段注入 —— 以下是毛泽东本人的真实文字。请吸收其句式节奏、措辞习惯、比喻方式，但不要机械复制。让输出读起来像自然的毛体，不是拼凑。】');
    fragments.forEach(function (f, i) {
      parts.push('片段' + (i + 1) + '（' + f.work + '）：' + f.text);
    });

    if (pd.samples && pd.samples.length > 0) {
      parts.push('');
      parts.push('【时期风格参照】');
      pd.samples.forEach(function (s, i) {
        parts.push('参照' + (i + 1) + '：' + s);
      });
    }

    return parts.join('\n');
  }

