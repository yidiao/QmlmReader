  function pickFragments(period, text, n) {
    n = n || 3;
    var periodNum = { standard: 0, period1: 1, period2: 2, period3: 3 }[period] || 0;

    // 按关键词相关度排序
    if (text && text.length > 0) {
      var scored = FRAGMENTS.map(function (f) {
        var score = 0;
        var words = f.text.split('').filter(function (c) { return /[一-鿿]/.test(c); });
        words.forEach(function (w) {
          if (text.indexOf(w) >= 0) score++;
        });
        return { fragment: f, score: score };
      });
      scored.sort(function (a, b) { return b.score - a.score; });
      var picked = [], rest = [];
      scored.forEach(function (s) {
        if (picked.length >= n) return;
        if (s.fragment.period === periodNum || s.fragment.period === 0) {
          if (picked.length < Math.ceil(n * 0.7)) picked.push(s.fragment);
          else rest.push(s.fragment);
        } else {
          rest.push(s.fragment);
        }
      });
      while (picked.length < n && rest.length > 0) picked.push(rest.shift());
      return picked;
    }

    // 随机选取
    var pool = FRAGMENTS.slice();
    for (var i = pool.length - 1; i > 0; i--) {
      var j = Math.floor(Math.random() * (i + 1));
      var tmp = pool[i]; pool[i] = pool[j]; pool[j] = tmp;
    }
    var picked2 = [], rest2 = [];
    pool.forEach(function (f) {
      if (picked2.length >= n) return;
      if (f.period === periodNum || f.period === 0) {
        if (picked2.length < Math.ceil(n * 0.7)) picked2.push(f);
        else rest2.push(f);
      } else {
        rest2.push(f);
      }
    });
    while (picked2.length < n && rest2.length > 0) picked2.push(rest2.shift());
    return picked2;
  }

  function buildPrompt(text, period, inputType, fragments) {
    period = period || 'standard';
    var pd = PERIODS[period] || PERIODS['standard'];
    if (!fragments || !Array.isArray(fragments) || fragments.length === 0) fragments = pickFragments(period, text, 3);

    var parts = [pd.systemPrompt];

    // 经典片段注入
    parts.push('');
    parts.push('【经典片段注入——以下是恩格斯本人的真实文字。请将其让步结构、材料驱动方式、科学化语气融入你的输出。不要复制——但要让人读出"恩格斯的思维习惯"。】');
    fragments.forEach(function (f, i) {
      parts.push('片段' + (i + 1) + '（' + f.work + '）：' + f.text);
    });

    // 时期风格参照
    if (pd.samples && pd.samples.length > 0) {
      parts.push('');
      parts.push('【时期风格参照】');
      pd.samples.forEach(function (s, i) {
        parts.push('参照' + (i + 1) + '：' + s);
      });
    }

    // 输入类型 → 风格强度调制
    if (inputType) {
      parts.push('');
      parts.push('【风格强度——根据输入类型调整】');
      var guide = {
        casual: '轻松模式——使用"不错……但问题在于……"做一次轻度让步推进。保持原文的社交意图。不需要全面展开论证。',
        personal: '温和上升——从个人经验出发→一般规律→理论定位。一次"诚然……然而……"结构就够了。保持温暖的语气。',
        factual: '材料分析模式——"事实表明……""数据说明……"。归纳上升1-2层。可以加一句"举一个例子——"。',
        opinion: '教科书模式——使用完整的让步推进结构。二分/三分法组织分析。"诚然……但是……因此……"全文可用2-3次。',
        abstract: '理论展开模式——从概念出发，"当我们考察X时，首先呈现在我们眼前的是……"。科学类比1-2处。层次分明。'
      };
      var intensity = guide[inputType] || guide['opinion'];
      parts.push(intensity);
    }

    return parts.join('\n');
  }

